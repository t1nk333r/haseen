//! The command line, as the Go command had it: Go's flag package (one or
//! two dashes, `=value` or the next argument, `--` ends the flags), its
//! messages and exit codes (2 for usage, 1 for a failed generation), the
//! usage text, and the output (compared with the Go command's while both
//! existed, plan 167).

use std::path::PathBuf;
use std::process::Command;

const BIN: &str = env!("CARGO_BIN_EXE_haseen-palette");

const USAGE: &str = "Usage: haseen-palette [--light] [--mode MODE] [--json] <image>

  -json
    \tprint the palette as JSON instead of colors.toml
  -light
    \tgenerate a light palette
  -mode string
    \textraction mode: normal, monochromatic, analogous, pastel, material, colorful, muted, bright, complementary, triadic, split-complementary, tetradic, high-contrast, duotone (default \"normal\")
  -version
    \tprint the version and exit
";

fn corpus(name: &str) -> String {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/corpus")
        .join(name)
        .display()
        .to_string()
}

/// stdout, stderr, exit code, with a private cache.
fn run(args: &[&str]) -> (String, String, i32) {
    static N: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let n = N.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let cache = std::env::temp_dir().join(format!("haseen-palette-cli-{}-{n}", std::process::id()));
    let out = Command::new(BIN)
        .args(args)
        .env("HASEEN_PALETTE_CACHE", &cache)
        .output()
        .expect("run haseen-palette");
    let _ = std::fs::remove_dir_all(&cache);
    (
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
        out.status.code().unwrap_or(-1),
    )
}

#[test]
fn help_and_usage() {
    for flag in ["-h", "--help", "-help"] {
        assert_eq!(
            run(&[flag]),
            (String::new(), USAGE.to_string(), 0),
            "{flag}"
        );
    }
    assert_eq!(run(&[]), (String::new(), USAGE.to_string(), 2));
    let img = corpus("png-rgb8.png");
    assert_eq!(run(&[&img, "extra"]), (String::new(), USAGE.to_string(), 2));
}

#[test]
fn flag_errors_are_gos() {
    for (args, msg) in [
        (&["-x"][..], "flag provided but not defined: -x"),
        (&["--mode"][..], "flag needs an argument: -mode"),
        (
            &["-json=maybe"][..],
            "invalid boolean value \"maybe\" for -json: parse error",
        ),
        (&["---x"][..], "bad flag syntax: ---x"),
        (&["-=1"][..], "bad flag syntax: -=1"),
    ] {
        assert_eq!(
            run(args),
            (String::new(), format!("{msg}\n{USAGE}"), 2),
            "{args:?}"
        );
    }
}

#[test]
fn the_version_comes_from_the_build() {
    let want = option_env!("HASEEN_VERSION").unwrap_or("dev");
    assert_eq!(run(&["-version"]).0, format!("{want}\n"));
    assert_eq!(run(&["--version", "ignored.png"]).0, format!("{want}\n"));
}

#[test]
fn both_spellings_and_values() {
    let img = corpus("png-rgb8.png");
    let (out, err, code) = run(&["--light=false", "-json", &img]);
    assert_eq!((err.as_str(), code), ("", 0));
    assert!(
        out.starts_with("{\"seed\":\"fc2373053888bae9")
            && out.contains("\"light\":false,\"cached\":false"),
        "{out}"
    );
    // An empty mode is the default one.
    let (out, _, code) = run(&["-mode=", &img]);
    assert_eq!(code, 0);
    assert!(out.starts_with(
        "# Generated by `haseen theme wallpaper`: seed fc2373053888bae9, normal, dark.\n"
    ));
    let (out, _, code) = run(&["-mode=fire", "-light", "--", &img]);
    assert_eq!(code, 0);
    assert!(
        out.contains(", fire, light.\n") && out.contains("mode = \"light\"\n"),
        "{out}"
    );
}

#[test]
fn failures_exit_1() {
    let (out, err, code) = run(&["--mode", "nonsense", &corpus("png-rgb8.png")]);
    assert_eq!(
        (out.as_str(), err.as_str(), code),
        (
            "",
            "haseen-palette: unknown extraction mode \"nonsense\"\n",
            1
        )
    );
    let (_, err, code) = run(&["--", "-json"]);
    assert_eq!(
        (err.as_str(), code),
        (
            "haseen-palette: read -json: open -json: no such file or directory\n",
            1
        )
    );
    let img = corpus("bad-huge-header.png");
    let (_, err, code) = run(&[&img]);
    assert_eq!(
        (err.as_str(), code),
        ("haseen-palette: extract colours: failed to decode image: unsafe image dimensions 30000x10\n", 1)
    );
}
